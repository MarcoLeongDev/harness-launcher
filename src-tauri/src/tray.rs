//! Tray icon + menu (macOS menu bar). The launcher runs menubar-only:
//! no Dock icon, window hides instead of closing, quit only from the tray.
//! Engine-related items reflect the live engine phase (refresh()).
use tauri::menu::{Menu, MenuItem, PredefinedMenuItem};
use tauri::tray::{MouseButton, MouseButtonState, TrayIconBuilder, TrayIconEvent};
use tauri::{AppHandle, Manager};

use crate::state::AppState;

/// Handles to tray items that mirror engine state, stored in AppState so
/// commands can enable/disable them as the engine phase changes.
#[derive(Clone)]
pub struct TrayState {
    pub start: MenuItem<tauri::Wry>,
    pub stop: MenuItem<tauri::Wry>,
    pub restart: MenuItem<tauri::Wry>,
    pub force: MenuItem<tauri::Wry>,
}

/// Update tray item enablement from the current engine phase.
pub fn refresh(app: &AppHandle) {
    let st = app.state::<AppState>();
    let Some(items) = st.tray_state.lock().unwrap().clone() else {
        return;
    };
    let running = st.runtime.phase() != crate::runtime::PHASE_STOPPED;
    let _ = items.start.set_enabled(!running);
    let _ = items.stop.set_enabled(running);
    let _ = items.restart.set_enabled(running);
    let _ = items.force.set_enabled(running);
}

pub fn setup_tray(app: &AppHandle) -> tauri::Result<()> {
    let open = MenuItem::with_id(app, "open", "Open Harness", true, None::<&str>)?;
    let settings = MenuItem::with_id(app, "settings", "Control Panel…", true, None::<&str>)?;
    let start = MenuItem::with_id(app, "start", "Start Harness", false, None::<&str>)?;
    let stop = MenuItem::with_id(app, "stop", "Stop Harness", false, None::<&str>)?;
    let restart = MenuItem::with_id(app, "restart", "Restart Harness", false, None::<&str>)?;
    let force = MenuItem::with_id(app, "force", "Force Restart Harness", false, None::<&str>)?;
    let browser = MenuItem::with_id(app, "browser", "Open in Browser", true, None::<&str>)?;
    let update = MenuItem::with_id(app, "update", "Update Harness…", true, None::<&str>)?;
    let quit = MenuItem::with_id(app, "quit", "Quit DeepSeek Harness Launcher", true, None::<&str>)?;
    let sep = PredefinedMenuItem::separator(app)?;
    let menu = Menu::with_items(
        app,
        &[
            &open,
            &settings,
            &sep,
            &start,
            &stop,
            &restart,
            &force,
            &sep,
            &browser,
            &update,
            &sep,
            &quit,
        ],
    )?;

    *app.state::<AppState>().tray_state.lock().unwrap() = Some(TrayState { start, stop, restart, force });

    // Logo-derived black glyphs render crisply in the macOS menu bar as a
    // template image (generated by scripts/gen-icons.mjs at prep time).
    let icon = tauri::image::Image::from_bytes(include_bytes!("../resources/tray/tray-icon.png")).ok();
    let mut builder = TrayIconBuilder::with_id("main")
        .tooltip("DeepSeek Harness Launcher")
        .menu(&menu)
        .icon_as_template(true);
    if let Some(icon) = icon {
        builder = builder.icon(icon);
    }

    builder
        .on_menu_event(|app, event| match event.id().as_ref() {
            "open" => {
                let _ = show_main_window(app);
            }
            "settings" => {
                let _ = crate::window::open_settings_window(app);
            }
            "start" => {
                let handle = app.clone();
                tauri::async_runtime::spawn(async move {
                    let _ = crate::commands::engine_start(handle).await;
                });
            }
            "stop" => {
                let handle = app.clone();
                tauri::async_runtime::spawn(async move {
                    let _ = crate::commands::engine_stop(handle);
                });
            }
            "restart" => {
                let handle = app.clone();
                tauri::async_runtime::spawn(async move {
                    let _ = crate::commands::engine_restart(handle).await;
                });
            }
            "force" => {
                let handle = app.clone();
                tauri::async_runtime::spawn(async move {
                    let _ = crate::commands::engine_force_restart(handle).await;
                });
            }
            "browser" => {
                let _ = crate::commands::open_in_browser(app.clone());
            }
            "update" => {
                let handle = app.clone();
                tauri::async_runtime::spawn(async move {
                    let _ = crate::commands::update_to_latest(handle).await;
                });
            }
            "quit" => {
                let _ = crate::commands::quit_app(app.clone());
            }
            _ => {}
        })
        .on_tray_icon_event(|tray, event| {
            if let TrayIconEvent::Click {
                button: MouseButton::Left,
                button_state: MouseButtonState::Up,
                ..
            } = event
            {
                let app = tray.app_handle();
                let _ = show_main_window(app);
            }
        })
        .build(app)?;
    Ok(())
}

pub fn show_main_window(app: &AppHandle) -> Result<(), String> {
    let running = app.state::<AppState>().runtime.is_running();
    if let Some(window) = app.get_webview_window("main") {
        let _ = window.show();
        let _ = window.set_focus();
        if !running {
            let _ = crate::window::navigate(app, "dsh-ui://localhost/stopped");
        }
        return Ok(());
    }
    if running {
        crate::window::ensure_window(
            app,
            &crate::commands::harness_web_url(app, current_port(app), Some(std::time::Duration::from_secs(5))),
        )
    } else {
        crate::window::ensure_window(app, "dsh-ui://localhost/stopped")
    }
}

fn current_port(app: &AppHandle) -> u16 {
    *app.state::<AppState>().effective_port.lock().unwrap()
}
